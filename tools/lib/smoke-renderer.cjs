// Shared full-flow test, evaluated inside the real sandboxed renderer.
module.exports = async function smokeRenderer() {
            const assert = (condition, message) => { if (!condition) throw new Error(message); };
            const sleep = milliseconds => new Promise(resolve => setTimeout(resolve, milliseconds));
            const until = async (condition, label) => { for (let i = 0; i < 200; i++) { if (condition()) return; await sleep(25); } throw new Error('Timed out: ' + label); };
            await until(() => !!window.game, 'engine initialization');
            const game = window.game;
            if (game.isStartupSetupOpen()) { game.selectStartupLanguage('zh'); game.confirmStartupSetup(); }
            await until(() => game.startupMenuShown, 'startup menu');
            assert(getComputedStyle(document.querySelector('#start-btn')).fontSize !== '0px', 'Text button must be visible without artwork');
            assert(document.querySelector('#message-btn').hidden, 'Chat is opt-in');
            assert(document.querySelector('#cg-btn').hidden, 'CG gallery is opt-in');
            assert(!document.querySelector('[src="undefined"]'), 'Undefined resource URL');
            const menuTitle = document.querySelector('.title').textContent;
            game.openSettings();
            assert(game.gameState === 'modal', 'Settings opens');
            game.handleLanguageChange('en');
            assert(document.title === 'Your Story', 'English project title');
            game.closeSettings();
            game.handleLanguageChange('zh');
            game.startGame();
            await until(() => game.currentSceneId === 'start' && game.gameState === 'dialogue', 'first chapter');
            game.skipToNextScene();
            assert(game.gameState === 'choice', 'Choice is reached');
            assert(document.querySelectorAll('#choice-container button').length === 2, 'Both choices exist');
            document.querySelector('#choice-container button').click();
            await until(() => game.currentSceneId === 'lights' && game.gameState === 'dialogue', 'first branch');
            assert(RuntimeState.getFlag('visited_lights') === true, 'Branch flag saved');
            game.skipToNextScene();
            await until(() => game.currentSceneId === 'chapter_two' && game.gameState === 'dialogue', 'second chapter');
            assert(document.querySelector('.character-placeholder'), 'Text-only character card renders');
            assert(RuntimeState.getUnlocked('chapters').includes('chapter-02'), 'Chapter unlocked');
            game.openHistory();
            assert(document.querySelector('#history-content').textContent.length > 0, 'History is populated');
            game.closeHistory();
            game.openCharacterGallery();
            game.showCharDetail(GameConfig.characters.guide);
            assert(document.querySelector('#char-detail-name').textContent, 'Character profile opens without an image');
            game.closeCharacterGallery();
            game.openLoadMenu();
            assert(document.querySelectorAll('#load-menu-content button').length === 2, 'Chapter menu comes from configuration');
            game.closeLoadMenu();
            game.skipToNextScene();
            await until(() => game.gameState === 'choice', 'second choice');
            document.querySelectorAll('#choice-container button')[1].click();
            await until(() => game.gameState === 'minigame', 'rhythm entry');
            assert(!document.querySelector('#rhythm-game-container .arcade-card-actions button').disabled, 'Rhythm can start without art');
            document.querySelector('#rhythm-game-container .arcade-card-actions button').click();
            await sleep(150);
            game.endActivity();
            await game.loadScene('arcade_fight');
            assert(!document.querySelector('#fighting-game-container .arcade-card-actions button').disabled, 'Fight can start without art');
            document.querySelector('#fighting-game-container .arcade-card-actions button').click();
            await sleep(150);
            game.endActivity();
            await game.loadScene('arcade_snow');
            assert(!document.querySelector('#dodgeball-game-container .arcade-card-actions button').disabled, 'Snow game can start without art');
            document.querySelector('#dodgeball-game-container .arcade-card-actions button').click();
            await sleep(150);
            game.endActivity();
            await game.loadScene('arcade_writing');
            assert(document.querySelector('#writing-game-container canvas'), 'Writing canvas initialized');
            game.endActivity();
            await game.loadScene('credits');
            game.skipToNextScene();
            await until(() => game.endingCreditsActive, 'credits');
            game.endingCreditsSkip.click();
            await until(() => SaveManager.get('cleared', false), 'story completion');
            assert(!document.querySelector('[src="undefined"]'), 'No invalid image URL after all features');
            await AchievementManager.refresh();
            return { menuTitle, completed: true, placeholders: document.querySelectorAll('.character-placeholder').length,
                languageScenes: Object.keys(GameConfig.languages).reduce((sum, language) => sum + Object.keys(StoryRepository.getManifest(language)).length, 0) };
        };
